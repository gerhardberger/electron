import {
  createPublicKey,
  hkdfSync,
  randomBytes,
} from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

function argumentsByName(values) {
  const result = new Map();
  for (let index = 0; index < values.length; index += 2) {
    const name = values[index];
    const value = values[index + 1];
    if (!name?.startsWith('--') || value === undefined)
      throw new Error('arguments must use --name value');
    const key = name.slice(2);
    if (result.has(key)) throw new Error(`duplicate --${key}`);
    result.set(key, value);
  }
  return result;
}

function required(args, name) {
  const value = args.get(name);
  if (value === undefined) throw new Error(`missing --${name}`);
  return value;
}

function array(name, value) {
  const rows = [];
  for (let offset = 0; offset < value.length; offset += 12) {
    rows.push(`    ${[...value.subarray(offset, offset + 12)]
      .map(byte => `0x${byte.toString(16).padStart(2, '0')}`)
      .join(', ')}`);
  }
  return `inline constexpr std::array<uint8_t, ${value.length}> ${name} = {\n${rows.join(',\n')}\n};`;
}

function mix64(value) {
  value = BigInt.asUintN(64, value);
  value ^= value >> 30n;
  value = BigInt.asUintN(64, value * 0xbf58476d1ce4e5b9n);
  value ^= value >> 27n;
  value = BigInt.asUintN(64, value * 0x94d049bb133111ebn);
  return BigInt.asUintN(64, value ^ (value >> 31n));
}

const args = argumentsByName(process.argv.slice(2));
const verificationKey = createPublicKey(readFileSync(required(args, 'verification-key')));
if (verificationKey.asymmetricKeyType !== 'ed25519') throw new Error('verification key must be Ed25519');
const publicDer = verificationKey.export({ type: 'spki', format: 'der' });
const publicKey = publicDer.subarray(publicDer.length - 32);
const wrapKey = readFileSync(required(args, 'wrap-key'));
if (wrapKey.length !== 32) throw new Error('wrapping key must contain exactly 32 bytes');

const runtimeIdArgument = args.get('runtime-id');
const runtimeId = runtimeIdArgument === undefined
  ? randomBytes(16)
  : Buffer.from(runtimeIdArgument, 'hex');
if (runtimeId.length !== 16) throw new Error('runtime id must contain 32 hexadecimal characters');

const platformKeys = [];
for (const [platform, condition] of [
  ['windows', 'defined(_WIN32)'],
  ['macos', 'defined(__APPLE__)'],
  ['linux', 'defined(__linux__)'],
]) {
  const platformKey = Buffer.from(hkdfSync('sha256', wrapKey, runtimeId, `Plasticity JSC wrap ${platform}`, 32));
  const wrapKeySeed = randomBytes(8).readBigUInt64LE();
  let state = wrapKeySeed ^ runtimeId.readBigUInt64LE();
  const encodedWrapKey = Buffer.alloc(32);
  for (let index = 0; index < encodedWrapKey.length; ++index) {
    state = mix64(state + 0x9e3779b97f4a7c15n + BigInt(index));
    encodedWrapKey[index] = platformKey[index] ^ Number((state >> BigInt((index % 8) * 8)) & 0xffn);
  }
  platformKeys.push(`${platformKeys.length === 0 ? '#if' : '#elif'} ${condition}
inline constexpr uint64_t kWrapKeySeed = 0x${wrapKeySeed.toString(16).padStart(16, '0')}ULL;
${array('kEncodedWrapKey', encodedWrapKey)}`);
  platformKey.fill(0);
}
const output = required(args, 'output');
writeFileSync(output, `// Generated by tools/generate-key-header.mjs.
#ifndef PLASTICITY_SECURE_SRC_KEY_CONFIG_H_
#define PLASTICITY_SECURE_SRC_KEY_CONFIG_H_

#include <array>
#include <cstdint>

namespace plasticity::secure {

#define PLASTICITY_MANIFEST_PUBLIC_KEY_HEX "${publicKey.toString('hex')}"
${array('kRuntimeId', runtimeId)}
${platformKeys.join('\n')}
#else
#error Unsupported Plasticity platform
#endif

}  // namespace plasticity::secure

#endif  // PLASTICITY_SECURE_SRC_KEY_CONFIG_H_
`);
wrapKey.fill(0);

console.log(`generated ${output} for runtime ${runtimeId.toString('hex')}`);
